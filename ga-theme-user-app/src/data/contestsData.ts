export interface Contest {
  id: string;
  gameCategory: string; // e.g. 'BR FULL MAP', 'FREE MATCH', 'CLASH SQUAD 1V1', 'SOLO SURVIVAL', 'LONE WOLF 1V1', 'CS 4V4'
  status: 'ongoing' | 'upcoming' | 'resulted';
  title: string;
  time: string;
  prizePool: number;
  perKill: number;
  entryFee: number;
  type: string;
  entryPerPlayer: number;
  map: string;
  team?: string; // e.g. 'SOLO', 'DUO', 'SQUAD', '1V1'
  spotsTotal: number;
  spotsFilled: number;
  bannerType: 'solo-br' | 'duo-br' | 'squad-br' | 'cs-1v1' | 'lone-wolf';
  thumbnailUrl?: string;
  isJoined?: boolean;
  userIgn?: string;
  roomId?: string;
  roomPassword?: string;
  youtubeLiveUrl?: string;
}

export const getContestTeam = (contest: Contest): string => {
  if (contest.team) return contest.team;
  const titleUpper = (contest.title || '').toUpperCase();
  if (titleUpper.includes('DUO') || contest.bannerType === 'duo-br') return 'DUO';
  if (titleUpper.includes('SQUAD') || titleUpper.includes('4V4') || contest.bannerType === 'squad-br') return 'SQUAD';
  if (titleUpper.includes('1V1') || contest.bannerType === 'cs-1v1' || contest.bannerType === 'lone-wolf') return '1V1';
  if (titleUpper.includes('SOLO') || contest.bannerType === 'solo-br') return 'SOLO';
  return 'SOLO';
};

